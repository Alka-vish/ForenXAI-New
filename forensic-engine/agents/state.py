from typing import TypedDict, List, Dict, Any, Optional

class DebateMessage(TypedDict):
    """
    Standard schema for a single debate turn by either Prosecutor or Defence.
    """
    agent: str  # "prosecutor" or "defence"
    turn: int   # 1, 2, 3, 4
    argument: str
    supporting_evidence_ids: List[str]
    uncertainties: List[str]
    alternative_explanations: List[str]


class EvidenceSufficiency(TypedDict, total=False):
    """
    Status of evidence availability and debate continuation checks.
    """
    can_proceed: bool
    status: str
    reason: Optional[str]
    missing_evidence: List[str]


class ExpertReport(TypedDict, total=False):
    """
    Verification report generated by the Expert Agent.
    """
    status: str
    evidence_sufficient: bool
    verified_claims: List[Dict[str, Any]]
    unsupported_claims: List[Dict[str, Any]]
    hallucination_flags: List[Dict[str, Any]]
    contradictions: List[Dict[str, Any]]
    missing_information: List[str]
    reliability_concerns: List[str]
    recommendation: str  # "proceed_to_judge" or "stop"
    explanation: str


class JudgeResult(TypedDict, total=False):
    """
    Final forensic assessment generated by the Judge Agent.
    """
    status: str
    assessment: str  # "REAL", "FAKE", or "UNCERTAIN"
    reasoning: str
    supporting_evidence_ids: List[str]
    contradictory_evidence_ids: List[str]
    limitations: List[str]
    expert_verification_summary: str


class ForensicDebateState(TypedDict, total=False):
    """
    Complete typed state for the LangGraph four-agent debate system.
    """
    image_id: str
    analysis_result: Dict[str, Any]
    evidence: List[Dict[str, Any]]
    prosecutor_turns: List[DebateMessage]
    defence_turns: List[DebateMessage]
    debate_messages: List[DebateMessage]
    current_iteration: int
    evidence_sufficiency: Dict[str, Any]
    stopping_reason: Optional[str]
    expert_report: Optional[ExpertReport]
    judge_result: Optional[JudgeResult]
    processing_errors: List[str]
